export function buildRoutineDays(anchorDate: Date): RoutineDay[] {
  const monday = startOfWeek(anchorDate);

  return ROUTINE_DAY_DEFINITIONS.map((routineDay, index) => {
    const date = startOfDay(monday);
    date.setDate(monday.getDate() + index);

    return {
      ...routineDay,
      date,
      dateLabel: capitalizeLabel(ROUTINE_DATE_LABEL.format(date)),
    };
  });
}
